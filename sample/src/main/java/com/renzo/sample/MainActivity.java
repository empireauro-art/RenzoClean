package com.renzo.sample;

import android.app.Activity;
import android.content.ActivityNotFoundException;
import android.content.Intent;
import android.os.Bundle;
import android.webkit.WebSettings;
import android.widget.Button;
import android.widget.LinearLayout;
import android.widget.TextView;
import android.widget.Toast;

/** Test exporter. Every value below is a fixture, never a real SDK identifier. */
public class MainActivity extends Activity {
    private static final String EXTRA_PROVIDER = "com.renzo.idscanner.extra.PROVIDER";
    @Override
    protected void onCreate(Bundle b) {
        super.onCreate(b);
        String ua = WebSettings.getDefaultUserAgent(this);

        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setPadding(28, 48, 28, 28);

        TextView title = new TextView(this);
        title.setText("RENZO Diagnostic Exporter — TEST FIXTURES ONLY");
        root.addView(title);

        TextView note = new TextView(this);
        note.setText("These are sample values for testing provider labels and copying. They are not generated by AppsFlyer, Adjust, or Singular SDKs.");
        root.addView(note);

        root.addView(makeButton("Export AppsFlyer fixture", "appsflyer",
                "c737bcbb-995e-4d9a-b077-308734ff6a98|1793979555295-5083449865490225941|d378b55b4b36c5db|" + ua));
        root.addView(makeButton("Export Adjust fixture", "adjust",
                "TEST_ADJUST_ADID_0001|" + ua));
        root.addView(makeButton("Export Singular fixture", "singular",
                "TEST_SINGULAR_DEVICE_ID_0001|" + ua));
        setContentView(root);
    }

    private Button makeButton(String label, String provider, String record) {
        Button button = new Button(this);
        button.setText(label);
        button.setOnClickListener(v -> export(provider, record));
        return button;
    }

    private void export(String provider, String record) {
        Intent i = new Intent(Intent.ACTION_SEND)
                .setType("text/plain")
                .putExtra(Intent.EXTRA_TEXT, record)
                .putExtra(EXTRA_PROVIDER, provider)
                .setPackage("com.renzo.idscanner");
        try {
            startActivityForResult(i, provider.hashCode() & 0x7fff);
        } catch (ActivityNotFoundException e) {
            Toast.makeText(this, "RENZO ID Scanner is not installed", Toast.LENGTH_LONG).show();
        }
    }
}
